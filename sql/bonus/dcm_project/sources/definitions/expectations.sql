-- Data quality ships WITH the pipeline: every operator deployed from this project
-- gets the same invariants on day one. Custom DMFs come from the central DQ_COMMON schema.
ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT
    TO TABLE {{db}}.{{schema}}.MEMBERS__MEMBER
    ON (MEMBER_ID)
    EXPECTATION NO_DUPLICATE_MEMBERS (value = 0);

ATTACH DATA METRIC FUNCTION {{db}}.DQ_COMMON.FOREIGN_OPERATOR_ROWS
    TO TABLE {{db}}.{{schema}}.MEMBERS__MEMBER
    ON (OPERATOR_ID)
    EXPECTATION NO_OTHER_OPERATOR_ROWS (value = 0);

ATTACH DATA METRIC FUNCTION {{db}}.DQ_COMMON.ACTIVE_BUT_LEFT
    TO TABLE {{db}}.{{schema}}.MEMBERS__MEMBER
    ON (STATUS, LEFT_ON)
    EXPECTATION NO_ACTIVE_LEAVERS (value = 0);

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.NEGATIVE_COUNT
    TO TABLE {{db}}.{{schema}}.SYSTEM__PAYMENT
    ON (AMOUNT)
    EXPECTATION NO_NEGATIVE_AMOUNTS (value = 0);

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT
    TO DYNAMIC TABLE {{db}}.{{schema}}.REPORTING__DAILY_REVENUE
    ON (NET_REVENUE)
    EXPECTATION REVENUE_ALWAYS_COMPUTED (value = 0);
